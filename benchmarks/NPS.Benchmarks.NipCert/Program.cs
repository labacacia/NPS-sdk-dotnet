// NPS-RFC-0002 prototype empirical-data benchmark. Measures:
//
//   1. IdentFrame wire size — v1 (proprietary, no cert chain) vs
//      v2 (X.509 chain attached).  RFC §8.4 threshold: v2 IdentFrame
//      with Ed25519 leaf + single-level intermediate MUST NOT exceed
//      1200 bytes.
//
//   2. Verification latency — how long the verifier spends on Step 3
//      (signature) plus Step 3b (X.509 chain).  RFC §8.4 target: <= 50 µs
//      per cert on typical hardware; <= 5x regression vs v1 acceptable.
//
// Run:
//   dotnet run --project impl/dotnet/benchmarks/NPS.Benchmarks.NipCert
//   dotnet run --project impl/dotnet/benchmarks/NPS.Benchmarks.NipCert -- --emit
//
// --emit also writes the Markdown report under
// docs/benchmarks/nip-cert-prototype.md so the RFC §9 Empirical Data
// table can be regenerated reproducibly.

using System.Diagnostics;
using System.Text;
using System.Text.Json;
using NPS.NIP;
using NPS.NIP.Ca;
using NPS.NIP.Crypto;
using NPS.NIP.Frames;
using NPS.NIP.Verification;
using NPS.NIP.X509;
using NSec.Cryptography;

bool emit = args.Contains("--emit");

// ── Build a CA + agent fixture in-memory ────────────────────────────────────

var tempDir = Path.Combine(Path.GetTempPath(), "nps-bench-" + Guid.NewGuid().ToString("N"));
Directory.CreateDirectory(tempDir);
try
{
    using var caKeys = new NipKeyManager();
    caKeys.Generate(Path.Combine(tempDir, "ca.key.enc"), "bench");

    var caOpts = new NipCaOptions
    {
        CaNid                 = "urn:nps:org:ca.bench.example",
        KeyFilePath           = Path.Combine(tempDir, "ca.key.enc"),
        KeyPassphrase         = "bench",
        BaseUrl               = "https://ca.bench.example",
        AgentCertValidityDays = 30,
        NodeCertValidityDays  = 90,
        RenewalWindowDays     = 7,
    };
    var ca = new NipCaService(caOpts, new InMemBenchStore(), caKeys);

    using var caRoot = NipX509Builder.IssueRoot(
        caOpts.CaNid, caKeys.PrivateKey,
        DateTimeOffset.UtcNow.AddMinutes(-1),
        DateTimeOffset.UtcNow.AddYears(5),
        RandomSerial());

    using var agentKey = Key.Create(SignatureAlgorithm.Ed25519, new KeyCreationParameters
    {
        ExportPolicy = KeyExportPolicies.AllowPlaintextExport,
    });
    var agentPub = NipSigner.EncodePublicKey(agentKey.PublicKey);

    var v1Frame = await ca.RegisterAsync(
        "agent", "bench-v1", agentPub,
        new[] { "nwp:query" },
        """{"nodes":["nwp://api.bench.example/*"]}""");
    var v2Frame = await ca.RegisterX509Async(
        "agent", "bench-v2", agentPub,
        new[] { "nwp:query" },
        """{"nodes":["nwp://api.bench.example/*"]}""",
        caRoot,
        AssuranceLevel.Anonymous);

    // ── Wire size measurement ────────────────────────────────────────────────

    var jsonOpts = new JsonSerializerOptions
    {
        PropertyNamingPolicy   = JsonNamingPolicy.SnakeCaseLower,
        DefaultIgnoreCondition = System.Text.Json.Serialization.JsonIgnoreCondition.WhenWritingNull,
    };

    var v1Bytes = Encoding.UTF8.GetByteCount(JsonSerializer.Serialize(v1Frame, jsonOpts));
    var v2Bytes = Encoding.UTF8.GetByteCount(JsonSerializer.Serialize(v2Frame, jsonOpts));
    var deltaBytes = v2Bytes - v1Bytes;

    // ── Verification latency measurement ─────────────────────────────────────

    var verifierV1 = new NipIdentVerifier(new NipVerifierOptions
    {
        TrustedIssuers = new() { [caOpts.CaNid] = ca.GetCaPublicKey() },
    });
    var verifierV2 = new NipIdentVerifier(new NipVerifierOptions
    {
        TrustedIssuers   = new() { [caOpts.CaNid] = ca.GetCaPublicKey() },
        TrustedX509Roots = new[] { caRoot },
    });

    const int warmup = 200;
    const int iters  = 2_000;

    // Warm both paths.
    for (int i = 0; i < warmup; i++)
    {
        await verifierV1.VerifyAsync(v1Frame);
        await verifierV2.VerifyAsync(v2Frame);
    }

    var v1Latency = await TimeAsync(verifierV1, v1Frame, iters);
    var v2Latency = await TimeAsync(verifierV2, v2Frame, iters);

    var latencyRatio = v2Latency.TotalMicroseconds / v1Latency.TotalMicroseconds;

    // ── Report ───────────────────────────────────────────────────────────────

    var sb = new StringBuilder();
    sb.AppendLine("# NPS-RFC-0002 — Prototype Empirical Data");
    sb.AppendLine();
    sb.AppendLine($"*Generated by `NPS.Benchmarks.NipCert` on {DateTime.UtcNow:O}*");
    sb.AppendLine();
    sb.AppendLine("## Wire size — IdentFrame JSON encoding");
    sb.AppendLine();
    sb.AppendLine("| Variant | Bytes | Δ vs v1 | Notes |");
    sb.AppendLine("|---------|-------|---------|-------|");
    sb.AppendLine($"| v1 (proprietary CA-signed JSON, no cert chain) | {v1Bytes} | — | baseline |");
    sb.AppendLine($"| v2 (v1 fields + X.509 leaf + self-signed root, base64url DER) | {v2Bytes} | +{deltaBytes} | RFC §8.4 budget: ≤ 1200 B |");
    sb.AppendLine();
    sb.AppendLine($"**Result:** v2 IdentFrame is {v2Bytes} bytes, " +
        (v2Bytes <= 1200 ? "within" : "EXCEEDS") + " the §8.4 1200-byte target.");
    sb.AppendLine();

    sb.AppendLine("## Verification latency");
    sb.AppendLine();
    sb.AppendLine($"Iterations per variant: {iters} (after {warmup} warm-up).");
    sb.AppendLine();
    sb.AppendLine("| Verifier path | Mean per call | Notes |");
    sb.AppendLine("|---------------|---------------|-------|");
    sb.AppendLine($"| v1 (Ed25519 only) | {v1Latency.TotalMicroseconds:F2} µs | baseline |");
    sb.AppendLine($"| v2 (v1 + X.509 chain check) | {v2Latency.TotalMicroseconds:F2} µs | {latencyRatio:F2}× v1 |");
    sb.AppendLine();
    sb.AppendLine($"RFC §8.4 target: ≤ 50 µs per cert on typical hardware; ≤ 5× regression acceptable.");
    sb.AppendLine();
    sb.AppendLine($"**Result:** v2 path is {(v2Latency.TotalMicroseconds <= 50.0 ? "within" : "above")} the absolute 50 µs target; " +
        $"regression vs v1 is {latencyRatio:F2}× ({(latencyRatio <= 5.0 ? "within" : "above")} the 5× ceiling).");
    sb.AppendLine();

    sb.AppendLine("## Methodology notes");
    sb.AppendLine();
    sb.AppendLine("- Same Ed25519 agent key is used in both v1 and v2 issuance, so the only varying inputs are the cert chain and the `cert_format` discriminator.");
    sb.AppendLine("- v2 cert chain is leaf + self-signed root (1 intermediate hop); RFC §8.4 budget assumes leaf + single-level intermediate, so the actual production size could be marginally higher.");
    sb.AppendLine("- Latency measured via `Stopwatch.GetTimestamp()` over a tight loop of `await verifier.VerifyAsync(frame)` calls; absolute numbers depend on host CPU — useful for ratio only.");

    var report = sb.ToString();
    Console.WriteLine(report);

    if (emit)
    {
        var repoRoot = FindRepoRoot();
        var outPath  = Path.Combine(repoRoot, "docs", "benchmarks", "nip-cert-prototype.md");
        Directory.CreateDirectory(Path.GetDirectoryName(outPath)!);
        File.WriteAllText(outPath, report, new UTF8Encoding(false));
        Console.Error.WriteLine($"Report written to {outPath}");
    }
}
finally
{
    try { Directory.Delete(tempDir, recursive: true); } catch { /* best effort */ }
}

return 0;

static async Task<TimeSpan> TimeAsync(NipIdentVerifier verifier, IdentFrame frame, int iters)
{
    // Stopwatch.ElapsedTicks is in `Stopwatch.Frequency` units, NOT TimeSpan
    // ticks — divide by Frequency to get seconds.
    var sw = Stopwatch.StartNew();
    for (int i = 0; i < iters; i++)
        await verifier.VerifyAsync(frame);
    sw.Stop();
    return TimeSpan.FromSeconds((double)sw.ElapsedTicks / Stopwatch.Frequency / iters);
}

static byte[] RandomSerial()
{
    var b = new byte[16];
    System.Security.Cryptography.RandomNumberGenerator.Fill(b);
    b[0] &= 0x7F;
    if (b[0] == 0) b[0] = 0x01;
    return b;
}

static string FindRepoRoot()
{
    var dir = AppContext.BaseDirectory;
    while (dir is not null && !Directory.Exists(Path.Combine(dir, ".git")))
        dir = Path.GetDirectoryName(dir);
    return dir ?? throw new InvalidOperationException("repo root not found.");
}

// ── In-memory store sufficient for the benchmark's single-shot issuance ─────

internal sealed class InMemBenchStore : INipCaStore
{
    private readonly List<NipCertRecord> _records = new();
    private long _serial;

    public Task SaveAsync(NipCertRecord record, CancellationToken ct = default)
    {
        _records.Add(record);
        return Task.CompletedTask;
    }
    public Task<NipCertRecord?> GetByNidAsync(string nid, CancellationToken ct = default) =>
        Task.FromResult<NipCertRecord?>(
            _records.Where(r => r.Nid == nid).MaxBy(r => r.IssuedAt));
    public Task<NipCertRecord?> GetBySerialAsync(string serial, CancellationToken ct = default) =>
        Task.FromResult<NipCertRecord?>(_records.FirstOrDefault(r => r.Serial == serial));
    public Task<bool> RevokeAsync(string nid, string reason, DateTime revokedAt, CancellationToken ct = default)
        => Task.FromResult(true);
    public Task<string> NextSerialAsync(CancellationToken ct = default) =>
        Task.FromResult($"0x{Interlocked.Increment(ref _serial):X}");
    public Task<IReadOnlyList<NipCertRecord>> GetRevokedAsync(CancellationToken ct = default) =>
        Task.FromResult<IReadOnlyList<NipCertRecord>>(Array.Empty<NipCertRecord>());
    public Task<IReadOnlyList<NipCertRecord>> GetByParentNidAsync(string parentNid, CancellationToken ct = default) =>
        Task.FromResult<IReadOnlyList<NipCertRecord>>(
            _records.Where(r => r.ParentNid == parentNid).ToList());
}
